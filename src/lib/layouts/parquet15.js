import { assignSharedEdges } from './tiling'

// Geometry for the "standard parquet jigsaw 15" .fjsw template:
// a 12-piece rosette of 8 equilateral triangles and 4 squares, all with the
// same edge length, carrying 15 question/answer pairs on its shared edges.
//
// WHERE THIS COMES FROM, since the template was previously left unimplemented
// over a licensing question (docs/PROJECT.md §7a). That question was about
// copying `jigsaw-generator`'s GPL-3 layout table — its per-piece slot
// assignment and coordinates. Nothing here is taken from it. The arrangement
// below is reconstructed from the two non-GPL lines of evidence already
// recorded in that section, plus the angle arithmetic they force:
//
//   - a published prose description of the template set: "a 12 piece 'oval'
//     parquet puzzle made up of 4 squares and 8 triangles", with two central
//     triangles pointing up and down, four tilted squares around them and six
//     triangles forming the outer rim;
//   - the slot arithmetic done here before any source was found: 8x3 + 4x4 =
//     40 edge slots = 2x15 pairs + 10 border edges.
//
// Given that description the figure is forced, and the construction below is
// the derivation rather than a guess:
//
//   1. The two central triangles share an edge, making a 60/120 rhombus.
//   2. A square sits on each of the rhombus's four edges.
//   3. At each rhombus vertex, what is left to 360 degrees is exactly filled
//      by triangles. At a 60-degree vertex: 60 + 90 + 90 leaves 120, which is
//      two triangles. At a 120-degree vertex: 120 + 90 + 90 leaves 60, which
//      is one. The rhombus has two of each, so 2x2 + 2x1 = 6 rim triangles —
//      the six the description calls for, with nothing left over.
//
// The count is then checked, not assumed: the shared edges are derived from
// the coordinates by assignSharedEdges, and come out as 15 pairs and 10
// border edges. Three independent routes — prose, arithmetic and geometry —
// agreeing is what makes this the shape rather than a plausible shape.
//
// WHICH PAIR SITS ON WHICH EDGE is ours, generated by assignSharedEdges in
// reading order. That is the part the GPL file would have supplied, and it is
// the part that turns out not to be needed: because both the cut-out pieces
// and the answer key are drawn from this one layout, any assignment that puts
// an answer on its own question's edge produces a solvable puzzle. It does
// mean the pieces may sit in different places than the desktop app would put
// them — a different arrangement of the same puzzle, not a wrong one.

export const PARQUET_SIDE = 700

const H = Math.sqrt(3) / 2

// Coordinates are rounded so that two pieces meeting along an edge name its
// endpoints identically. The constructions below land within ~1e-15 of each
// other, so 4 decimal places at unit scale separates "the same point" from
// "a different point" by eleven orders of magnitude.
const round = (v) => Math.round(v * 1e4) / 1e4
const sub = (a, b) => [a[0] - b[0], a[1] - b[1]]
const add = (a, b) => [a[0] + b[0], a[1] + b[1]]
const dot = (a, b) => a[0] * b[0] + a[1] * b[1]
const unit = (a) => {
  const l = Math.hypot(a[0], a[1])
  return [a[0] / l, a[1] / l]
}
const midpoint = (a, b) => [(a[0] + b[0]) / 2, (a[1] + b[1]) / 2]

function buildRosette() {
  // The central rhombus: two equilateral triangles sharing the edge A-B.
  const A = [0, 0]
  const B = [1, 0]
  const C = [0.5, H]
  const D = [0.5, -H]
  const centre = [0.5, 0]

  const polygons = [
    [A, B, C],
    [A, D, B],
  ]

  // The rhombus's own edges, and the outward direction from each.
  const edges = [
    [A, C],
    [C, B],
    [B, D],
    [D, A],
  ]
  const normals = edges.map(([p, q]) => {
    const d = unit(sub(q, p))
    const n = [-d[1], d[0]]
    // Whichever of the two perpendiculars points away from the middle.
    return dot(n, sub(midpoint(p, q), centre)) > 0 ? n : [-n[0], -n[1]]
  })

  // A square standing on each rhombus edge.
  edges.forEach(([p, q], i) => {
    const n = normals[i]
    polygons.push([p, q, add(q, n), add(p, n)])
  })

  // Rim triangles, filling what is left at each rhombus vertex. `edgesAt`
  // names the two rhombus edges meeting there; the squares on those edges
  // each reach one unit along that edge's normal, and the wedge between those
  // two arms is the gap.
  const corners = [
    { v: A, edgesAt: [0, 3] },
    { v: C, edgesAt: [0, 1] },
    { v: B, edgesAt: [1, 2] },
    { v: D, edgesAt: [2, 3] },
  ]
  for (const { v, edgesAt } of corners) {
    const [n1, n2] = edgesAt.map((i) => normals[i])
    const arm1 = add(v, n1)
    const arm2 = add(v, n2)
    // Both arms are unit length, so the wedge between them is 60 degrees when
    // one triangle fills it and 120 when two do. cos 120 = -0.5.
    if (dot(n1, n2) < -0.25) {
      // Two triangles, meeting along the bisector. Each then has two unit
      // sides 60 degrees apart, which makes it equilateral.
      const mid = add(v, unit(add(n1, n2)))
      polygons.push([v, arm1, mid])
      polygons.push([v, mid, arm2])
    } else {
      polygons.push([v, arm1, arm2])
    }
  }

  return polygons
}

// Unit coordinates -> drawing units, with y flipped because SVG's y axis
// points down, and shifted so the figure starts at the origin.
function toDrawingUnits(polygons) {
  const flipped = polygons.map((poly) => poly.map(([x, y]) => [x, -y]))
  const xs = flipped.flat().map((p) => p[0])
  const ys = flipped.flat().map((p) => p[1])
  const minX = Math.min(...xs)
  const minY = Math.min(...ys)
  return flipped.map((poly) =>
    poly.map(([x, y]) => [round(x - minX) * PARQUET_SIDE, round(y - minY) * PARQUET_SIDE]),
  )
}

const shapes = toDrawingUnits(buildRosette())

// A polygon's edges, in the same order as its `slots`: edge i runs from
// point i to point i+1.
const polygonEdges = (piece) =>
  piece.points.map((p, i) => [p, piece.points[(i + 1) % piece.points.length]])

export function buildParquetLayout({ layoutId = 'parquet-15', fillBorder = false } = {}) {
  const pieces = shapes.map((points) => ({ points }))
  const { slots, pairCount, borderCount } = assignSharedEdges(pieces, polygonEdges, { fillBorder })
  return {
    layoutId,
    shape: 'polygon-tiling',
    pairCount: pairCount + borderCount,
    matchedPairCount: pairCount,
    // Flagged for the same reason as square-24, and with the same limit on
    // what the flag means: the shape and the pair count are solid, and the
    // puzzle solves by construction. What is unconfirmed is only whether the
    // desktop app would put the same pair on the same edge.
    verified: false,
    unverifiedReason:
      "The 12-piece shape is reconstructed rather than copied from a reference, and which pair sits on which edge is this app's own choice. The puzzle does solve — every answer is on its own question's edge — but the pieces may not be arranged the way the desktop app would print them.",
    pieces: pieces.map((piece, i) => ({ points: piece.points, slots: slots[i] })),
  }
}

const parquet15 = buildParquetLayout()

export default parquet15
